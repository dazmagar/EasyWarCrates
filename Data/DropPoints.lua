-- Same table in map fractions. Built once at load; the percent table above
-- stays the editable one.
local frac = {}
for mapID, spots in pairs(PCT) do
    local t = {}
    for i = 1, #spots do
        local s = spots[i]
        t[i] = { x = s[1] * 0.01, y = s[2] * 0.01, n = s[3] }
    end
    frac[mapID] = t
end

ns.DropPointsPct = PCT
ns.DropPoints = frac

-- The shipped catalogue, never edited at runtime. Track/Learn.lua layers the
-- player's own sightings on top and owns ns.GetDropPoints, which is what the
-- rest of the addon asks for.
function ns.ShippedDropPoints(mapID)
    return frac[mapID]
end
